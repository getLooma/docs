#!/usr/bin/env node
// `just routes`: append every new page route to published-routes.txt (never remove one), and,
// with --caddy <dist>, render redirects.json into <dist>/_redirects.caddy for the production
// Caddyfile (design.md D8). openspec change docs-site.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { readPages } from './lib/pages.mjs';

export function readManifest(file) {
  if (!fs.existsSync(file)) return [];
  return fs
    .readFileSync(file, 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'));
}

const HEADER =
  '# Every route the docs site has ever published. Append-only: `just routes` adds new pages.\n' +
  '# A route that is no longer a page must be a "from" in redirects.json (just check enforces it).\n';

/** The manifest with every current page route appended; existing lines keep their order. */
export function appendRoutes(manifest, routes) {
  const seen = new Set(manifest);
  return [...manifest, ...routes.filter((r) => !seen.has(r)).sort()];
}

export function writeManifest(file, routes) {
  fs.writeFileSync(file, HEADER + routes.join('\n') + '\n');
}

/** Caddy `redir` lines; `/old/` also matches `/old` (the slashless form). */
export function renderCaddy(redirects) {
  const lines = ['# Generated by scripts/routes.mjs from redirects.json. Do not edit.'];
  for (const { from, to } of redirects) {
    lines.push(`redir ${from} ${to} permanent`);
    if (from.endsWith('/') && from !== '/')
      lines.push(`redir ${from.slice(0, -1)} ${to} permanent`);
  }
  return lines.join('\n') + '\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = '.';
  const caddyIndex = process.argv.indexOf('--caddy');
  if (caddyIndex !== -1) {
    const dist = process.argv[caddyIndex + 1] ?? 'dist';
    const redirects = JSON.parse(fs.readFileSync(path.join(root, 'redirects.json'), 'utf8'));
    fs.writeFileSync(path.join(dist, '_redirects.caddy'), renderCaddy(redirects));
    console.log(`routes: wrote ${dist}/_redirects.caddy (${redirects.length} redirects)`);
  } else {
    const file = path.join(root, 'published-routes.txt');
    const before = readManifest(file);
    const after = appendRoutes(
      before,
      readPages().map((p) => p.route)
    );
    writeManifest(file, after);
    console.log(`routes: ${after.length - before.length} new route(s) recorded`);
  }
}
